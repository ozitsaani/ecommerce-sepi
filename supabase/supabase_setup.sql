-- 3a. Profil otomatis saat user mendaftar
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'full_name', ''), split_part(coalesce(new.email, 'pengguna'), '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 3b. Nama pengulas diisi server (tidak bisa dipalsukan klien)
create or replace function public.set_reviewer_name()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.user_id is not null then
    select p.full_name into new.reviewer_name from public.profiles p where p.id = new.user_id;
  end if;
  if new.reviewer_name is null or new.reviewer_name = '' then
    new.reviewer_name := 'Pengguna Sepi';
  end if;
  return new;
end;
$$;

-- Hanya jalan untuk ulasan buatan user. Data contoh (user_id kosong) tetap pakai nama sendiri.
drop trigger if exists trg_reviews_set_name on public.reviews;
create trigger trg_reviews_set_name
  before insert on public.reviews
  for each row when (new.user_id is not null)
  execute function public.set_reviewer_name();

-- 3c. Rating rata-rata produk dihitung ulang tiap ulasan berubah
create or replace function public.refresh_product_rating()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  pid uuid;
begin
  if tg_op = 'DELETE' then
    pid := old.product_id;
  else
    pid := new.product_id;
  end if;

  update public.products
     set rating_avg   = coalesce((select round(avg(r.rating)::numeric, 1) from public.reviews r where r.product_id = pid), 0),
         rating_count = (select count(*) from public.reviews r where r.product_id = pid)
   where id = pid;
  return null;
end;
$$;

drop trigger if exists trg_reviews_rating on public.reviews;
create trigger trg_reviews_rating
  after insert or update or delete on public.reviews
  for each row execute function public.refresh_product_rating();

-- 3d. Hanya satu alamat utama per user; alamat pertama otomatis jadi utama
create or replace function public.enforce_single_default_address()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' and not exists (select 1 from public.addresses a where a.user_id = new.user_id) then
    new.is_default := true;
  end if;
  if new.is_default then
    update public.addresses set is_default = false
     where user_id = new.user_id and id <> new.id and is_default;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_addresses_default on public.addresses;
create trigger trg_addresses_default
  before insert or update on public.addresses
  for each row execute function public.enforce_single_default_address();


