    'Lumayan, tapi warna sedikit berbeda dari foto.',
    'Sudah dipakai seminggu, aman dan nyaman.',
    'Worth it banget, packing tebal.'
  ];
begin
  if exists (select 1 from public.reviews where user_id is null) then
    return;
  end if;

  for p in select id from public.products loop
    for i in 1..5 loop
      h := abs(hashtext(p.id::text || i::text)) % 10;
      insert into public.reviews (product_id, reviewer_name, rating, comment, created_at)
      values (
        p.id,
        names[1 + abs(hashtext(p.id::text || 'n' || i::text)) % array_length(names, 1)],
        (case when h < 5 then 5 when h < 8 then 4 when h < 9 then 3 else 2 end)::smallint,
        comments[1 + abs(hashtext(p.id::text || 'c' || i::text)) % array_length(comments, 1)],
        now() - (i * interval '3 days')
      );
    end loop;
  end loop;
end;
