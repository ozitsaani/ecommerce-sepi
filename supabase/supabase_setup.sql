-- 6a. Tambah ke keranjang (jumlah ditambah bila item yang sama sudah ada)
create or replace function public.add_to_cart(
  p_product_id uuid,
  p_variant_id uuid default null,
  p_quantity   integer default 1
)
returns public.cart_items
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_stock integer;
  v_item  public.cart_items;
begin
  if v_uid is null then
    raise exception 'Silakan masuk terlebih dahulu';
  end if;
  if p_quantity is null or p_quantity < 1 then
    raise exception 'Jumlah minimal 1';
  end if;

  select stock into v_stock from public.products where id = p_product_id;
  if not found then
    raise exception 'Produk tidak ditemukan';
  end if;

  if p_variant_id is null and exists (select 1 from public.product_variants where product_id = p_product_id) then
    raise exception 'Pilih varian terlebih dahulu';
  end if;
  if p_variant_id is not null and not exists (
       select 1 from public.product_variants where id = p_variant_id and product_id = p_product_id) then
    raise exception 'Varian tidak valid';
  end if;

  select * into v_item
    from public.cart_items
   where user_id = v_uid and product_id = p_product_id and variant_id is not distinct from p_variant_id;

  if found then
    if v_item.quantity + p_quantity > v_stock then
      raise exception 'Stok tidak mencukupi (sisa %)', v_stock;
    end if;
    update public.cart_items
       set quantity = quantity + p_quantity
     where id = v_item.id
     returning * into v_item;
  else
    if p_quantity > v_stock then
      raise exception 'Stok tidak mencukupi (sisa %)', v_stock;
    end if;
    insert into public.cart_items (user_id, product_id, variant_id, quantity)
    values (v_uid, p_product_id, p_variant_id, p_quantity)
    returning * into v_item;
  end if;

  return v_item;
end;
$$;


-- 6b. Checkout: keranjang terpilih -> pesanan
create or replace function public.checkout(
  p_address_id      uuid,
  p_shipping_method text,
  p_voucher_code    text default null,
  p_cart_item_ids   uuid[] default null      -- null = semua isi keranjang
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid      uuid := auth.uid();
  v_addr     public.addresses;
  v_ship     integer;
  v_sub      bigint := 0;
  v_disc     integer := 0;
  v_total    integer;
  v_voucher  public.vouchers;
  v_order    public.orders;
  v_code     text;
  r          record;
begin
  if v_uid is null then
    raise exception 'Silakan masuk terlebih dahulu';
  end if;

  select * into v_addr from public.addresses where id = p_address_id and user_id = v_uid;
  if not found then
    raise exception 'Alamat pengiriman tidak ditemukan';
  end if;
  if lower(v_addr.city) not like 'cirebon%' then
    raise exception 'Pengiriman saat ini hanya tersedia untuk wilayah Cirebon';
  end if;

  v_ship := case upper(coalesce(p_shipping_method, ''))
              when 'REGULER' then 10000
              when 'EXPRESS' then 25000
              else null end;
  if v_ship is null then
    raise exception 'Opsi pengiriman tidak valid';
  end if;

  if not exists (
       select 1 from public.cart_items ci
        where ci.user_id = v_uid and (p_cart_item_ids is null or ci.id = any(p_cart_item_ids))) then
    raise exception 'Pilih minimal satu item di keranjang';
  end if;

  -- Kunci baris produk, cek stok, hitung subtotal
  for r in
    select ci.quantity, p.name, p.price, p.stock,
           coalesce(pv.price_delta, 0) as delta
      from public.cart_items ci
      join public.products p on p.id = ci.product_id
      left join public.product_variants pv on pv.id = ci.variant_id
     where ci.user_id = v_uid and (p_cart_item_ids is null or ci.id = any(p_cart_item_ids))
       for update of p
  loop
    if r.stock < r.quantity then
      raise exception 'Stok "%" tidak mencukupi (sisa %)', r.name, r.stock;
    end if;
    v_sub := v_sub + (r.price + r.delta)::bigint * r.quantity;
  end loop;

  -- Voucher (opsional)
  if p_voucher_code is not null and length(trim(p_voucher_code)) > 0 then
    select * into v_voucher
      from public.vouchers
     where upper(code) = upper(trim(p_voucher_code)) and is_active and valid_until > now();
    if not found then
      raise exception 'Kode voucher tidak valid atau sudah kedaluwarsa';
    end if;
    if v_sub < v_voucher.min_spend then
      raise exception 'Minimal belanja voucher ini Rp%',
        replace(to_char(v_voucher.min_spend, 'FM999,999,999'), ',', '.');
    end if;

    v_disc := case v_voucher.discount_type
      when 'PERCENT'       then least((v_sub * v_voucher.discount_value / 100)::integer, coalesce(v_voucher.max_discount, 2147483647))
      when 'FIXED'         then least(v_voucher.discount_value::bigint, v_sub)::integer
      when 'FREE_SHIPPING' then least(v_ship, coalesce(v_voucher.max_discount, v_ship))
      else 0 end;
  end if;

  v_total := (v_sub + v_ship - v_disc)::integer;

  -- Kode pesanan unik, contoh: SPI26100412345
  loop
    v_code := 'SPI' || to_char(now() at time zone 'Asia/Jakarta', 'YYMMDD')
              || lpad((floor(random() * 90000) + 10000)::integer::text, 5, '0');
    exit when not exists (select 1 from public.orders where order_code = v_code);
  end loop;

  insert into public.orders (
    order_code, user_id, recipient_name, recipient_phone, shipping_address,
    shipping_method, subtotal, shipping_cost, discount, total, voucher_code, payment_deadline
  ) values (
    v_code, v_uid, v_addr.recipient_name, v_addr.phone,
    concat_ws(', ', v_addr.street, nullif(v_addr.district, ''),
              v_addr.city || coalesce(' ' || nullif(v_addr.postal_code, ''), '')),
    upper(p_shipping_method), v_sub::integer, v_ship, v_disc, v_total,
    case when v_voucher.code is not null then v_voucher.code end,
    now() + interval '24 hours'
  ) returning * into v_order;

  -- Salin item ke pesanan dan kurangi stok
  for r in
    select ci.quantity, p.id as pid, p.name, p.price, p.image_url,
           pv.option_name, coalesce(pv.price_delta, 0) as delta, pv.group_name
      from public.cart_items ci
      join public.products p on p.id = ci.product_id
      left join public.product_variants pv on pv.id = ci.variant_id
     where ci.user_id = v_uid and (p_cart_item_ids is null or ci.id = any(p_cart_item_ids))
  loop
    insert into public.order_items (order_id, product_id, product_name, variant_label, image_url, unit_price, quantity)
    values (v_order.id, r.pid, r.name,
            case when r.option_name is not null then r.group_name || ': ' || r.option_name end,
            r.image_url, r.price + r.delta, r.quantity);

    update public.products
       set stock = stock - r.quantity,
           sold_count = sold_count + r.quantity
     where id = r.pid;
  end loop;

  delete from public.cart_items
   where user_id = v_uid and (p_cart_item_ids is null or id = any(p_cart_item_ids));

  insert into public.order_tracking (order_id, title, description, created_at)
  values (v_order.id, 'Pesanan dibuat', 'Menunggu pembayaran melalui Virtual Account BCA', clock_timestamp());

  return v_order;
end;
$$;


-- 6c. Pembayaran sandbox: tombol "Cek Status Pembayaran"
create or replace function public.simulate_payment(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_order public.orders;
begin
  if v_uid is null then
    raise exception 'Silakan masuk terlebih dahulu';
  end if;

  select * into v_order from public.orders where id = p_order_id and user_id = v_uid for update;
  if not found then
    raise exception 'Pesanan tidak ditemukan';
  end if;
  if v_order.status <> 'UNPAID' then
    raise exception 'Pesanan ini tidak sedang menunggu pembayaran';
  end if;
  if now() > v_order.payment_deadline then
    raise exception 'Batas waktu pembayaran sudah lewat. Batalkan pesanan lalu buat pesanan baru';
  end if;

  update public.orders set status = 'PAID', paid_at = now()
   where id = v_order.id returning * into v_order;

  insert into public.order_tracking (order_id, title, description, created_at)
  values (v_order.id, 'Pembayaran diterima', 'Pembayaran Virtual Account BCA berhasil (mode sandbox)', clock_timestamp());

  return v_order;
end;
$$;


-- 6d. Batalkan pesanan yang belum dibayar (stok dikembalikan)
create or replace function public.cancel_order(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_order public.orders;
  r       record;
begin
  if v_uid is null then
    raise exception 'Silakan masuk terlebih dahulu';
  end if;

  select * into v_order from public.orders where id = p_order_id and user_id = v_uid for update;
  if not found then
    raise exception 'Pesanan tidak ditemukan';
  end if;
  if v_order.status <> 'UNPAID' then
    raise exception 'Hanya pesanan yang belum dibayar yang bisa dibatalkan';
  end if;

  for r in select product_id, quantity from public.order_items where order_id = v_order.id and product_id is not null
  loop
    update public.products
       set stock = stock + r.quantity,
           sold_count = greatest(sold_count - r.quantity, 0)
     where id = r.product_id;
  end loop;

  update public.orders set status = 'CANCELLED' where id = v_order.id returning * into v_order;

  insert into public.order_tracking (order_id, title, description, created_at)
  values (v_order.id, 'Pesanan dibatalkan', 'Pesanan dibatalkan sebelum pembayaran', clock_timestamp());

  return v_order;
end;
$$;


-- 6e. MODE DEMO: majukan status pesanan satu langkah (PAID -> PACKED -> SHIPPED -> DELIVERED)
--     Dipakai tombol "Simulasikan langkah berikutnya" agar tracking dan ulasan bisa didemokan.
create or replace function public.advance_order(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_order public.orders;
  v_resi  text;
begin
  if v_uid is null then
    raise exception 'Silakan masuk terlebih dahulu';
  end if;

  select * into v_order from public.orders where id = p_order_id and user_id = v_uid for update;
  if not found then
    raise exception 'Pesanan tidak ditemukan';
  end if;

  if v_order.status = 'PAID' then
    update public.orders set status = 'PACKED' where id = v_order.id returning * into v_order;
    insert into public.order_tracking (order_id, title, description, created_at)
    values (v_order.id, 'Pesanan dikemas', 'Penjual sedang mengemas pesananmu', clock_timestamp());

  elsif v_order.status = 'PACKED' then
    v_resi := 'SPK' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 10));
    update public.orders set status = 'SHIPPED', tracking_number = v_resi
     where id = v_order.id returning * into v_order;
    insert into public.order_tracking (order_id, title, description, created_at)
    values (v_order.id, 'Paket diserahkan ke kurir', 'Kurir Sepi menjemput paket. No. resi ' || v_resi, clock_timestamp());
    insert into public.order_tracking (order_id, title, description, created_at)
    values (v_order.id, 'Paket dalam perjalanan', 'Paket menuju alamat tujuan di Cirebon', clock_timestamp());

  elsif v_order.status = 'SHIPPED' then
    update public.orders set status = 'DELIVERED' where id = v_order.id returning * into v_order;
    insert into public.order_tracking (order_id, title, description, created_at)
    values (v_order.id, 'Paket diterima', 'Paket telah diterima oleh ' || v_order.recipient_name, clock_timestamp());

  else
    raise exception 'Status pesanan tidak bisa dimajukan lagi';
  end if;

  return v_order;
end;
$$;


