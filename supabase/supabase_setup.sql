create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text not null default '',
  phone       text,
  avatar_url  text,
  created_at  timestamptz not null default now()
);

create table if not exists public.categories (
  id          integer generated by default as identity primary key,
  name        text not null unique,
  icon_key    text not null default 'tag',   -- nama ikon lokal di aplikasi
  sort_order  integer not null default 0
);

create table if not exists public.products (
  id              uuid primary key default gen_random_uuid(),
  slug            text not null unique,
  category_id     integer not null references public.categories(id),
  name            text not null,
  description     text not null default '',
  price           integer not null check (price >= 0),
  original_price  integer check (original_price is null or original_price >= price),
  image_url       text,
  stock           integer not null default 0 check (stock >= 0),
  sold_count      integer not null default 0 check (sold_count >= 0),
  rating_avg      numeric(2,1) not null default 0,
  rating_count    integer not null default 0,
  is_flash_sale   boolean not null default false,
  shop_name       text not null default 'Sepi Official',
  shop_city       text not null default 'Cirebon',
  created_at      timestamptz not null default now()
);

-- Satu produk punya paling banyak SATU grup varian (mis. "Warna" atau "Ukuran").
create table if not exists public.product_variants (
  id            uuid primary key default gen_random_uuid(),
  product_id    uuid not null references public.products(id) on delete cascade,
  group_name    text not null,
  option_name   text not null,
  price_delta   integer not null default 0,
  unique (product_id, group_name, option_name)
);

create table if not exists public.reviews (
  id             uuid primary key default gen_random_uuid(),
  product_id     uuid not null references public.products(id) on delete cascade,
  user_id        uuid references auth.users(id) on delete set null default auth.uid(),
  reviewer_name  text,
  rating         smallint not null check (rating between 1 and 5),
  comment        text not null default '',
  created_at     timestamptz not null default now()
);

create table if not exists public.cart_items (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  product_id  uuid not null references public.products(id) on delete cascade,
  variant_id  uuid references public.product_variants(id) on delete set null,
  quantity    integer not null default 1 check (quantity between 1 and 99),
  created_at  timestamptz not null default now()
);

create table if not exists public.addresses (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null default auth.uid() references auth.users(id) on delete cascade,
  label           text not null default 'Rumah',
  recipient_name  text not null,
  phone           text not null,
  street          text not null,
  district        text not null default '',
  city            text not null default 'Cirebon',
  postal_code     text not null default '',
  is_default      boolean not null default false,
  created_at      timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  product_id  uuid not null references public.products(id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.vouchers (
  code            text primary key,
  title           text not null,
  description     text not null default '',
  discount_type   text not null check (discount_type in ('PERCENT','FIXED','FREE_SHIPPING')),
  discount_value  integer not null default 0,
  min_spend       integer not null default 0,
  max_discount    integer,
  valid_until     timestamptz not null default (now() + interval '365 days'),
  is_active       boolean not null default true
);

create table if not exists public.orders (
  id                uuid primary key default gen_random_uuid(),
  order_code        text not null unique,
  user_id           uuid not null references auth.users(id) on delete cascade,
  status            text not null default 'UNPAID'
                    check (status in ('UNPAID','PAID','PACKED','SHIPPED','DELIVERED','CANCELLED')),
  recipient_name    text not null,
  recipient_phone   text not null,
  shipping_address  text not null,
  shipping_method   text not null check (shipping_method in ('REGULER','EXPRESS')),
  courier_name      text not null default 'Sepi Kurir',
  tracking_number   text,
  subtotal          integer not null,
  shipping_cost     integer not null,
  discount          integer not null default 0,
  total             integer not null,
  voucher_code      text,
  va_number         text not null default '1234567890',
  payment_deadline  timestamptz not null,
  paid_at           timestamptz,
  created_at        timestamptz not null default now()
);

create table if not exists public.order_items (
  id             uuid primary key default gen_random_uuid(),
  order_id       uuid not null references public.orders(id) on delete cascade,
  product_id     uuid references public.products(id) on delete set null,
  product_name   text not null,
  variant_label  text,
  image_url      text,
  unit_price     integer not null,
  quantity       integer not null check (quantity > 0)
