declare
  p record;
  i integer;
  h integer;
  names    text[] := array['Andini','Budi S.','Citra','Dimas','Eka P.','Fajar','Gita','Hendra','Indah','Joko','Kiki','Lina'];
  comments text[] := array[
    'Barang sesuai deskripsi, pengemasan rapi.',
